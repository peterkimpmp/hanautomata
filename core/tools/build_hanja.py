# Builds data/hanja.txt.gz from Unicode Unihan (Unihan_Readings.txt, Unihan_IRGSources.txt): reading <TAB> common <TAB> extended.
# common = KS X 1001 (kHangul source 0), basic educational hanja (source E) first, then KS X 1001 order (kIRG_KSource K0);
# extended = every other kHangul reading (KS X 1002, name hanja), by code point.
# Usage: python3 core/tools/build_hanja.py Unihan_Readings.txt Unihan_IRGSources.txt data/hanja.txt.gz
# (Unihan.zip from https://www.unicode.org/Public/UCD/latest/ucd/; the output is deterministic for one Unihan version.)
import gzip, sys
readings, ksource = sys.argv[1], sys.argv[2]
k0 = {}
for line in open(ksource, encoding="utf-8"):
    if "\tkIRG_KSource\t" in line:
        cp, _, value = line.rstrip("\n").split("\t")
        if value.startswith("K0-"):
            k0[int(cp[2:], 16)] = value
table = {}
for line in open(readings, encoding="utf-8"):
    if "\tkHangul\t" not in line:
        continue
    cp, _, value = line.rstrip("\n").split("\t")
    c = int(cp[2:], 16)
    for item in value.split(" "):
        reading, _, sources = item.partition(":")
        table.setdefault(reading, []).append((c, sources))
out = []
for reading in sorted(table):
    entries = table[reading]
    common = [e for e in entries if "0" in e[1]]
    common.sort(key=lambda e: ("E" not in e[1], k0.get(e[0], "K0-FFFF"), e[0]))
    seen = {e[0] for e in common}
    extended = sorted({e[0] for e in entries if e[0] not in seen})
    out.append(reading + "\t" + "".join(chr(e[0]) for e in common) + "\t" + "".join(chr(c) for c in extended))
data = ("# Hangul syllable -> hanja, from Unicode Unihan (Unicode License v3). Columns: reading, common (KS X 1001; basic"
        " educational hanja first), extended. Generated by core/tools/build_hanja.py.\n" + "\n".join(out) + "\n")
with gzip.GzipFile(sys.argv[3], "wb", mtime=0) as f:
    f.write(data.encode("utf-8"))
print(len(out), "readings", sum(len(l.split("\t")[1]) for l in out), "common", sum(len(l.split("\t")[2]) for l in out), "extended")
