    static IEnumerable<string[]> Rows(string path)
    {
        foreach (string line in File.ReadLines(path, Encoding.UTF8))
            if (line.Length > 0 && line[0] != '#') yield return line.Split('\t');
    }
    static IEnumerable<string> WordList(string path)
    {
        using (var gzip = new GZipStream(File.OpenRead(path), CompressionMode.Decompress))
        using (var reader = new StreamReader(gzip, Encoding.UTF8))
        {
            string line;
            while ((line = reader.ReadLine()) != null) if (line.Length > 0 && line[0] != '#') yield return line.Trim();
        }
    }
    static bool LoneSurrogate(string s)
    {
        for (int i = 0; i < s.Length; i++)
        {
            if (char.IsHighSurrogate(s[i])) { if (i + 1 >= s.Length || !char.IsLowSurrogate(s[i + 1])) return true; i++; }
            else if (char.IsLowSurrogate(s[i])) return true;
        }
        return false;
    }
    static string SwapCase(string s)
    {
        var sb = new StringBuilder(s.Length);
        foreach (char c in s) sb.Append(c >= 'a' && c <= 'z' ? (char)(c - 32) : c >= 'A' && c <= 'Z' ? (char)(c + 32) : c);
        return sb.ToString();
    }
    static string Capitalize(string s) { return s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1); }
    static bool IsSyllable(char c) { return c >= 0xac00 && c <= 0xd7a3; }
    static long Bits(double value) { return BitConverter.DoubleToInt64Bits(value); }
    static string Random(Rng rng, string[] tokens, int min, int max)
    {
        int n = min + rng.Next(max - min + 1); var sb = new StringBuilder();
        for (int i = 0; i < n; i++) sb.Append(tokens[rng.Next(tokens.Length)]);
        return sb.ToString();
    }
    static string[] Weighted(params (string Tokens, int Weight)[] groups)
    {
        var list = new List<string>();
        foreach (var group in groups)
            foreach (string token in group.Tokens.Split(' ', StringSplitOptions.RemoveEmptyEntries))
                for (int i = 0; i < group.Weight; i++) list.Add(token.Replace("␠", " ").Replace("␤", "\n"));
        return list.ToArray();
    }
    static readonly string[] LetterTokens = Weighted(("a b c d e f g h i j k l m n o p q r s t u v w x y z", 4), ("Q W E R T O P", 2), ("A B C D F G H I J K L M N S U V X Y Z", 1));
    static readonly string[] KeyTokens = Weighted(("a b c d e f g h i j k l m n o p q r s t u v w x y z", 6), ("Q W E R T O P", 2),
