// Golden extractor for the Rust core parity gate (G1). Runs the shipped C# engine over fixed and generated inputs and
// writes gzip JSON Lines that core/tests/parity.rs replays. Every row carries its inputs, so the Rust side never
// regenerates them. Deterministic: fixed LCG seeds, explicit profile paths, repository files only.
//   dotnet run --project tests/dotnet/Hanautomata.Golden -c Release -- [--out DIR] [--lite N] [--unicode FILE]
//   dotnet run --project tests/dotnet/Hanautomata.Golden -c Release -- --latency tests/corpora/intelligence-v014.tsv
// --lite N keeps every Nth generated row (hand-written rows are always kept); --unicode writes core/src/unicode_tables.rs.
// The 4,000 + 4,000 sensitivity samples (tests/lm/out-*, regenerated by build_lm.py, not committed) join the full suite when present.
