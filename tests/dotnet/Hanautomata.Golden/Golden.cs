    sealed class Rng
    {
        ulong state;
        public Rng(ulong seed) { state = seed; }
        public int Next(int n) { state = state * 6364136223846793005UL + 1442695040888963407UL; return (int)((state >> 33) % (ulong)n); }
        public T Pick<T>(IReadOnlyList<T> items) { return items[Next(items.Count)]; }
    }

    sealed class Lines : IDisposable
    {
        readonly FileStream file; readonly GZipStream gzip; int bulk;
        public int Count;
        public Lines(string path) { file = File.Create(path); gzip = new GZipStream(file, CompressionLevel.SmallestSize); }
        // The body runs only for kept rows, so skipped rows cost nothing in lite mode.
        public void Write(bool important, Action<Utf8JsonWriter> body)
        {
            if (!important && lite > 0 && bulk++ % lite != 0) return;
            var buffer = new MemoryStream();
            using (var writer = new Utf8JsonWriter(buffer, new JsonWriterOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }))
            { writer.WriteStartObject(); body(writer); writer.WriteEndObject(); }
            buffer.WriteByte((byte)'\n'); buffer.Position = 0; buffer.CopyTo(gzip); Count++;
        }
        public void Dispose() { gzip.Dispose(); file.Dispose(); }
    }

    sealed class Item { public string Raw, Keys, Profile; public bool Important; }
    sealed class Inputs
    {
        readonly Dictionary<string, int> index = new Dictionary<string, int>(StringComparer.Ordinal);
        public readonly List<Item> Items = new List<Item>();
        public void Add(string raw, string keys, bool important, string profile = null)
        {
            if (raw == null || keys == null || raw.Length != keys.Length || LoneSurrogate(raw) || LoneSurrogate(keys)) return;
            string id = (profile ?? "") + "\u0001" + raw + "\u0001" + keys; int at;
            if (index.TryGetValue(id, out at)) { if (important) Items[at].Important = true; return; }
            index[id] = Items.Count; Items.Add(new Item { Raw = raw, Keys = keys, Important = important, Profile = profile });
        }
        // Typed text plus its Caps Lock form: literal case flips while the Korean keys keep the real Shift state.
        public void Typed(string text, bool important, string profile = null)
        {
            Add(text, text, important, profile);
            string caps = SwapCase(text); if (caps != text) Add(caps, text, important, profile);
        }
    }

