    static readonly string[] TextTokens = Weighted(("가 한 글 뷁 힣 각 값 닭 왅", 4), ("ㄱ ㅏ ㄳ ㅢ ㅃ \u1100 \u1161 \u11A8 \u11C2 \u1175", 2),
