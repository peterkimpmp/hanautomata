        }
    }

    // ---- Lists: hand-maintained vocabularies in enumeration order (trie insertion order breaks cost ties) -------------
    static object Field(Detector detector, string name)
    {
        var field = typeof(Detector).GetField(name, BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static);
        if (field == null) throw new InvalidOperationException("Detector field missing: " + name);
        return field.GetValue(field.IsStatic ? null : detector);
    }
    static int WriteLists(string path)
    {
