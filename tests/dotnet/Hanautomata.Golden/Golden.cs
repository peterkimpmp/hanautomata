                o.Write(item.Important, w =>
                {
                    string composed; int stray;
                    double ko = scorer.Korean(item.Keys, out composed, out stray), en = scorer.English(item.Raw);
                    var codes = new StringBuilder(); LanguageVerdict first = null;
                    foreach (string preset in Presets)
                    {
                        Configure(scorer, preset);
                        foreach (bool? prev in Prevs)
                        {
                            var v = scorer.Score(item.Raw, item.Keys, prev);
                            if (first == null) first = v;
                            else if (Bits(v.Llr) != Bits(first.Llr) || v.Lexical != first.Lexical || v.Composed != first.Composed)
                                throw new InvalidOperationException("score inputs drifted across presets: " + item.Raw);
                            char code = v.IsKorean ? 'K' : v.IsEnglish ? 'E' : 'U';
                            codes.Append(v.Nudged ? char.ToLowerInvariant(code) : code);
                        }
                    }
                    w.WriteString("raw", item.Raw); w.WriteString("keys", item.Keys);
                    w.WriteNumber("ko", Bits(ko)); w.WriteNumber("stray", stray); w.WriteString("composed", composed);
                    w.WriteNumber("en", Bits(en)); w.WriteNumber("llr", Bits(first.Llr)); w.WriteBoolean("lex", first.Lexical);
                    w.WriteString("v", codes.ToString());
                });
            Configure(scorer, "balanced");
            return o.Count;
        }
    }

