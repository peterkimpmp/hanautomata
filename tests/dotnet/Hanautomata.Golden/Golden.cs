    static string FindRepo()
    {
        var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "src", "Core.cs"))) dir = dir.Parent;
        if (dir == null) throw new InvalidOperationException("Run inside the hanautomata repository.");
        return dir.FullName;
