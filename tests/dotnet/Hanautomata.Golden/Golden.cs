        public void Step(Utf8JsonWriter w, Op op)
        {
            string[] a = op.Args;
            w.WriteStartObject(); w.WriteString("op", op.Name);
            w.WriteStartArray("a"); foreach (string s in a) w.WriteStringValue(s); w.WriteEndArray();
            if (op.Entries != null) { w.WriteStartArray("e"); foreach (LearnedWord e in op.Entries) Entry(w, e); w.WriteEndArray(); }
            w.WritePropertyName("x");
