                case "get2": { bool korean; bool found = P.TryGet(a[0], a[1], out korean); w.WriteStartArray(); w.WriteBooleanValue(found); w.WriteBooleanValue(korean); w.WriteEndArray(); break; }
                case "undo": w.WriteStartArray(); w.WriteBooleanValue(P.UndoLast()); State(w); w.WriteEndArray(); break;
                case "pclear": P.Clear(); w.WriteStartArray(); State(w); w.WriteEndArray(); break;
                case "enable": P.Enabled = a[0] == "1"; w.WriteStartArray(); w.WriteBooleanValue(P.Enabled); State(w); w.WriteEndArray(); break;
                case "export":
                {
                    int revision; LearnedWord[] entries = P.Export(out revision);
                    w.WriteStartObject(); w.WriteNumber("rev", revision); w.WriteStartArray("entries"); foreach (LearnedWord e in entries) Entry(w, e); w.WriteEndArray(); w.WriteEndObject(); break;
                }
                case "restore": P.Restore(op.Entries); w.WriteStartArray(); State(w); w.WriteEndArray(); break;
                case "ctxkey": w.WriteStringValue(WordPreferences.ContextKey(a[0])); break;
                case "dec": WriteDecision(w, D.Decide(a[0], a[1], a[2], Prev(a[3]))); break;
                case "cfg":
