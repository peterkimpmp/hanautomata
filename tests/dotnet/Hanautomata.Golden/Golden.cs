                    w.WriteStartArray(); w.WriteStringValue(name); w.WriteNumberValue(Bits(D.Scorer.KoreanThreshold)); w.WriteNumberValue(Bits(D.Scorer.EnglishThreshold)); w.WriteEndArray(); break;
                }
                case "cfgv":
                    D.Scorer.Configure(double.Parse(a[0], CultureInfo.InvariantCulture), double.Parse(a[1], CultureInfo.InvariantCulture));
                    w.WriteStartArray(); w.WriteNumberValue(Bits(D.Scorer.KoreanThreshold)); w.WriteNumberValue(Bits(D.Scorer.EnglishThreshold)); w.WriteEndArray(); break;
                case "type": foreach (char c in a[0]) C.Append(c, c); w.WriteNullValue(); break;
                case "app": C.Append(a[0][0], a[1][0]); w.WriteNullValue(); break;
                case "semi": C.Semicolon(); w.WriteNullValue(); break;
                case "bs": C.Backspace(); w.WriteNullValue(); break;
                case "tog": C.Toggle(); w.WriteNullValue(); break;
                case "conf": w.WriteBooleanValue(C.ConfirmSelection()); break;
                case "acc": C.AcceptCommit(a[0] == "1"); w.WriteNullValue(); break;
                case "reset": C.ResetContext(a[0], a[1] == "1"); w.WriteNullValue(); break;
                case "cclear": C.Clear(); w.WriteNullValue(); break;
                case "explicit": w.WriteBooleanValue(C.RememberExplicit(a[0], a[1], a[2] == "1", a[3])); break;
                case "lex": D.AddLexemeForTest(a[0], a[1] == "1", int.Parse(a[2], CultureInfo.InvariantCulture)); w.WriteNullValue(); break;
                case "newc": C = new Composition(D); w.WriteNullValue(); break;
                case "st":
                {
                    Decision current = C.Current; w.WriteStartArray();
                    w.WriteStringValue(current.Text); w.WriteStringValue(current.Alternative); w.WriteBooleanValue(current.IsKorean);
                    w.WriteStringValue(current.Reason); w.WriteStringValue(current.Confidence.ToString());
                    w.WriteStringValue(C.Raw); w.WriteStringValue(C.Keys); w.WriteStringValue(C.Context); Prev(w, C.PreviousKorean);
                    w.WriteBooleanValue(C.IsEmpty); w.WriteStringValue(C.Korean); w.WriteNumberValue(C.Length); w.WriteNumberValue(P.Count); w.WriteNumberValue(P.Version);
                    w.WriteEndArray(); break;
                }
                default: throw new InvalidOperationException("unknown op " + op.Name);
            }
            w.WriteEndObject();
        }
    }
