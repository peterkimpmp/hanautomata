    // ---- Unicode tables: .NET char semantics the engine depends on, for the BMP --------------------------------------
    static char Fold(char c) { char u = char.ToUpperInvariant(c); return string.Equals(c.ToString(), u.ToString(), StringComparison.OrdinalIgnoreCase) ? u : c; }
    static bool WriteUnicode(string path)
    {
        int mismatches = 0;
        for (int c = 0; c <= 0xffff; c++)
        {
            if (c >= 0xd800 && c <= 0xdfff) continue;
            char ch = (char)c, lower = char.ToLowerInvariant(ch), upper = char.ToUpperInvariant(ch);
            if (string.Equals(ch.ToString(), lower.ToString(), StringComparison.OrdinalIgnoreCase) != (Fold(ch) == Fold(lower))) mismatches++;
            if (string.Equals(ch.ToString(), upper.ToString(), StringComparison.OrdinalIgnoreCase) != (Fold(ch) == Fold(upper))) mismatches++;
            if (Fold(Fold(ch)) != Fold(ch)) mismatches++;
        }
        if (mismatches > 0) { Console.Error.WriteLine("OrdinalIgnoreCase is not a per-character fold on this runtime: " + mismatches + " mismatches"); return false; }
        var sb = new StringBuilder();
        sb.Append("// @generated by tests/dotnet/Hanautomata.Golden --unicode on ").Append(RuntimeInformation.FrameworkDescription).Append(". Do not edit.\n");
        sb.Append("// .NET char semantics for the Basic Multilingual Plane, as src/Core.cs observes them: char.IsLetter/IsUpper/IsLower\n");
        sb.Append("// (general categories L*, Lu, Ll), char.ToLowerInvariant, and the per-character fold behind StringComparer.OrdinalIgnoreCase.\n");
        sb.Append("// Surrogate code units are absent: .NET reports them as non-letters and leaves their case unchanged.\n\n");
        Ranges(sb, "LETTER", char.IsLetter); Ranges(sb, "UPPER", char.IsUpper); Ranges(sb, "LOWER", char.IsLower);
        Pairs(sb, "TO_LOWER", char.ToLowerInvariant); Pairs(sb, "FOLD", Fold);
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
        Console.WriteLine("unicode tables " + path);
        return true;
    }
    static void Ranges(StringBuilder sb, string name, Func<char, bool> test)
    {
        var items = new List<string>(); int start = -1;
        for (int c = 0; c <= 0x10000; c++)
        {
            bool inside = c <= 0xffff && !(c >= 0xd800 && c <= 0xdfff) && test((char)c);
            if (inside && start < 0) start = c;
            else if (!inside && start >= 0) { items.Add("(0x" + start.ToString("X4") + ", 0x" + (c - 1).ToString("X4") + ")"); start = -1; }
        }
        Table(sb, name, items);
    }
    static void Pairs(StringBuilder sb, string name, Func<char, char> map)
    {
        var items = new List<string>();
        for (int c = 0; c <= 0xffff; c++)
        {
            if (c >= 0xd800 && c <= 0xdfff) continue;
            char m = map((char)c); if (m != c) items.Add("(0x" + c.ToString("X4") + ", 0x" + ((int)m).ToString("X4") + ")");
        }
        Table(sb, name, items);
    }
    static void Table(StringBuilder sb, string name, List<string> items)
    {
        sb.Append("pub(crate) static ").Append(name).Append(": &[(u16, u16)] = &[\n");
        for (int i = 0; i < items.Count; i += 8) sb.Append("    ").Append(string.Join(", ", items.Skip(i).Take(8))).Append(",\n");
        sb.Append("];\n\n");
    }
