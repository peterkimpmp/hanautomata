    static readonly Regex LiteralPattern = new Regex("@\"(?:[^\"]|\"\")*\"|\"(?:[^\"\\\\\\r\\n]|\\\\.)*\"", RegexOptions.Compiled);
    static IEnumerable<string> Literals(string source)
    {
        foreach (Match m in LiteralPattern.Matches(source))
        {
            string value = m.Value, text;
            if (value[0] == '@') text = value.Substring(2, value.Length - 3).Replace("\"\"", "\"");
            else { try { text = Regex.Unescape(value.Substring(1, value.Length - 2)); } catch (ArgumentException) { continue; } }
            if (text.Length > 0 && text.Length <= 100) yield return text;
        }
    }
